def normalize_language(language):
    lang = (language or "en").lower()
    if lang.startswith("zh"):
        return "zh"
    return "en"


def get_language():
    return normalize_language(cfg.get("language", "en"))


def tr(key, **kwargs):
    lang = get_language()
    text = TRANSLATIONS.get(lang, {}).get(key, TRANSLATIONS["en"].get(key, key))
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


def language_items():
    return [(code, tr(f"settings.language.{code}")) for code in SUPPORTED_LANGUAGES]
